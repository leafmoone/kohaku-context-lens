export function normalizeLensLocale(rawLocale) {
  const text = String(rawLocale || "").trim().toLowerCase()
  if (text === "zh-tw" || text === "zh-hk" || text === "zh-mo" || text === "zh-hant") {
    return "zh-TW"
  }
  if (text === "zh" || text === "zh-cn" || text === "zh-sg" || text === "zh-hans" || text.startsWith("zh-")) {
    return "zh-CN"
  }
  return "en"
}

export function translateLensText(locale, key, params) {
  const normalized = normalizeLensLocale(locale)
  const bundle = BUNDLES[normalized] || BUNDLES.en
  const raw = bundle[key] !== undefined ? bundle[key] : BUNDLES.en[key]
  if (raw === undefined) return String(key)
  if (!params || typeof params !== "object") return raw
  return raw.replace(/\{(\w+)\}/g, (_match, name) => {
    const val = params[name]
    return val === undefined || val === null ? `{${name}}` : String(val)
  })
}

/**
 * Synchronize host Settings navigation item and SectionShell heading labels
 * to the active UI locale when KohakuTerrarium renders static manifest labels.
 */
export function syncSettingsHostLabels(locale, rootEl) {
  if (typeof document === "undefined") return
  const title = translateLensText(locale, "settings.title", null)

  const navButtons = document.querySelectorAll(`[data-section="${SETTINGS_SECTION_ID}"]`)
  for (const btn of navButtons) {
    const labelSpan = btn.querySelector("span.flex-1") || btn.querySelector("span:not([class*='i-'])")
    if (labelSpan && labelSpan.textContent !== title) {
      labelSpan.textContent = title
    }
  }

  if (rootEl && typeof rootEl.closest === "function") {
    const sectionEl = rootEl.closest("section")
    const heading = sectionEl ? sectionEl.querySelector("header h2") : null
    if (heading && heading.textContent !== title) {
      heading.textContent = title
    }
  }
}
